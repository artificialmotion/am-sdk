"""Generate ros2/am_description/urdf/am_units.urdf.xacro from the Python package's unit data.

Joint limits in the URDF come from the same numbers the simulators use (python/am_sdk/data):
effort = 2 s peak torque, velocity = 48 V no-load speed, friction = backdrive torque, and the
impedance K/D caps of the simulator envelope. Run this after any change to the unit data:

    python tools/gen_ros2_xacro.py

CI runs it with --check and fails when the generated file is out of date.
"""
import math
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "python"))

from am_sdk import units as U  # noqa: E402
from am_sdk.backends import sim as SIM  # noqa: E402

OUT = os.path.join(ROOT, "ros2", "am_description", "urdf", "am_units.urdf.xacro")


def g(x, digits=6):
    """Short, stable number formatting."""
    return ("%." + str(digits) + "g") % float(x)


def unit_values(unit):
    ud = U.load_unit(unit)
    wn = 2.0 * math.pi * SIM.ENVELOPE_HZ
    return {
        "unit": unit,
        "id": unit.replace("-", "_"),
        "peak": ud.peak_nm,
        "rated": ud.rated_nm,
        "vel": ud.no_load_rad_s["48"],
        "vel36": ud.no_load_rad_s["36"],
        "friction": ud.backdrive_nm,
        "armature": ud.armature_kgm2,
        "mass": ud.mass_kg,
        "ratio": ud.ratio,
        "kp_max": ud.armature_kgm2 * wn * wn,
        "kd_max": 2.0 * ud.armature_kgm2 * wn,
        "revision": ud.params.get("revision", ""),
    }


def generate() -> str:
    vals = [unit_values(u) for u in U.UNIT_IDS]
    units_py = "[" + ", ".join("'%s'" % v["unit"] for v in vals) + "]"
    L = []
    a = L.append
    a('<?xml version="1.0"?>')
    a("<!-- Generated by tools/gen_ros2_xacro.py from python/am_sdk/data. Do not edit. -->")
    a("<!-- SPDX-License-Identifier: Apache-2.0 -->")
    a("<!--")
    a("  Artificial Motion joints for URDF / ros2_control. Values are design targets for evaluation units")
    a("  shipping in Q1 2027, not measurements. All values are at the output shaft.")
    a("    effort   = 2 s peak torque (a 2 s event from a warm start, not a continuous rating)")
    a("    velocity = no-load speed at 48 V (the speed limit of the drive)")
    a("    friction = backdrive torque (Coulomb-like); damping is not specified (0)")
    a("  The continuous (thermal) torque and the speed-dependent torque curve are enforced by the drive")
    a("  and the am-sdk simulator, not by URDF limits. Actuator mass is NOT added to any link: add the")
    a("  am_<unit>_mass property to the link that carries the actuator.")
    a("")
    a("  Macros")
    a("    am_joint unit name parent child *origin lower upper axis")
    a("        revolute joint with this unit's limits (lower/upper are YOUR range of motion; the unit")
    a("        has no position limit of its own, default -pi..pi)")
    a("    am_<UNIT>_joint name parent child *origin lower upper axis      (UNIT = S_S S_D M H_F H_T H_X)")
    a("    am_ros2_control_joint name unit address default_stiffness default_damping sim_load_inertia")
    a("        the <joint> block inside <ros2_control> with every interface am_ros2_control provides")
    a("-->")
    a('<robot xmlns:xacro="http://www.ros.org/wiki/xacro">')
    a("")
    a("  <xacro:property name=\"am_units\" value=\"%s\"/>" % units_py)
    for v in vals:
        a("")
        a("  <!-- %s: gear ratio %s:1, reflected inertia %s kg m^2, rated (continuous) %s N m. %s -->"
          % (v["unit"], g(v["ratio"]), g(v["armature"]), g(v["rated"]), v["revision"]))
        for key, val in (("peak_torque", v["peak"]), ("rated_torque", v["rated"]),
                         ("velocity", v["vel"]), ("velocity_36v", v["vel36"]),
                         ("friction", v["friction"]), ("armature", v["armature"]), ("mass", v["mass"]),
                         ("gear_ratio", v["ratio"]), ("stiffness_max", v["kp_max"]),
                         ("damping_max", v["kd_max"])):
            a('  <xacro:property name="am_%s_%s" value="%s"/>' % (v["id"], key, g(val)))
        a('  <xacro:macro name="am_%s_joint" params="name parent child *origin lower:=${-pi} upper:=${pi} '
          "axis:='0 0 1'\">" % v["id"])
        a('    <joint name="${name}" type="revolute">')
        a('      <xacro:insert_block name="origin"/>')
        a('      <parent link="${parent}"/>')
        a('      <child link="${child}"/>')
        a('      <axis xyz="${axis}"/>')
        a('      <limit lower="${lower}" upper="${upper}" effort="${am_%s_peak_torque}" velocity="${am_%s_velocity}"/>'
          % (v["id"], v["id"]))
        a('      <dynamics damping="0.0" friction="${am_%s_friction}"/>' % v["id"])
        a("    </joint>")
        a("  </xacro:macro>")
    a("")
    a("  <!-- Unit dispatch. An unknown unit calls a macro that does not exist, so xacro stops with an error. -->")
    a("  <xacro:macro name=\"am_check_unit\" params=\"unit\">")
    a("    <xacro:unless value=\"${unit in am_units}\">")
    a("      <xacro:ERROR_unknown_am_unit_use_S_S_S_D_M_H_F_H_T_or_H_X unit=\"${unit}\"/>")
    a("    </xacro:unless>")
    a("  </xacro:macro>")
    a("")
    a('  <xacro:macro name="am_joint" params="unit name parent child *origin lower:=${-pi} upper:=${pi} '
      "axis:='0 0 1'\">")
    a('    <xacro:am_check_unit unit="${unit}"/>')
    for v in vals:
        a("    <xacro:if value=\"${unit == '%s'}\">" % v["unit"])
        a('      <xacro:am_%s_joint name="${name}" parent="${parent}" child="${child}" lower="${lower}" '
          'upper="${upper}" axis="${axis}">' % v["id"])
        a('        <xacro:insert_block name="origin"/>')
        a("      </xacro:am_%s_joint>" % v["id"])
        a("    </xacro:if>")
    a("  </xacro:macro>")
    a("")
    a("  <!-- ros2_control <joint> block for am_ros2_control/AmSystemInterface. Command limits are the unit's;")
    a("       address -1 = position of the joint in the ros2_control block; default_stiffness/damping empty =")
    a("       automatic (5 % of the K cap, 25 % of the D cap). -->")
    a("  <xacro:macro name=\"am_ros2_control_joint\" params=\"name unit address:=-1 default_stiffness:='' "
      "default_damping:='' sim_load_inertia:=0 sim_initial_position:=0\">")
    a('    <xacro:am_check_unit unit="${unit}"/>')
    for v in vals:
        i = v["id"]
        a("    <xacro:if value=\"${unit == '%s'}\">" % v["unit"])
        a('      <joint name="${name}">')
        a('        <param name="unit">%s</param>' % v["unit"])
        a('        <xacro:if value="${address >= 0}"><param name="address">${address}</param></xacro:if>')
        a("        <xacro:if value=\"${str(default_stiffness) != ''}\">"
          "<param name=\"default_stiffness\">${default_stiffness}</param></xacro:if>")
        a("        <xacro:if value=\"${str(default_damping) != ''}\">"
          "<param name=\"default_damping\">${default_damping}</param></xacro:if>")
        a('        <param name="sim_load_inertia">${sim_load_inertia}</param>')
        a('        <param name="sim_initial_position">${sim_initial_position}</param>')
        a('        <command_interface name="position"/>')
        a('        <command_interface name="velocity">')
        a('          <param name="min">${-am_%s_velocity}</param>' % i)
        a('          <param name="max">${am_%s_velocity}</param>' % i)
        a("        </command_interface>")
        a('        <command_interface name="effort">')
        a('          <param name="min">${-am_%s_peak_torque}</param>' % i)
        a('          <param name="max">${am_%s_peak_torque}</param>' % i)
        a("        </command_interface>")
        a('        <command_interface name="stiffness">')
        a('          <param name="min">0</param>')
        a('          <param name="max">${am_%s_stiffness_max}</param>' % i)
        a("        </command_interface>")
        a('        <command_interface name="damping">')
        a('          <param name="min">0</param>')
        a('          <param name="max">${am_%s_damping_max}</param>' % i)
        a("        </command_interface>")
        a('        <state_interface name="position"/>')
        a('        <state_interface name="velocity"/>')
        a('        <state_interface name="effort"/>')
        a('        <state_interface name="temperature"/>')
        a("      </joint>")
        a("    </xacro:if>")
    a("  </xacro:macro>")
    a("")
    a("</robot>")
    return "\n".join(L) + "\n"


def main():
    text = generate()
    if "--check" in sys.argv:
        with open(OUT, "r", encoding="utf-8") as fh:
            if fh.read() != text:
                raise SystemExit("am_units.urdf.xacro is out of date: run python tools/gen_ros2_xacro.py")
        print("am_units.urdf.xacro is up to date")
        return
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print("wrote", os.path.relpath(OUT, ROOT))


if __name__ == "__main__":
    main()
