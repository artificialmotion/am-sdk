"""Generate c/src/am_unit_data.c from the Python package's unit data (python/am_sdk/data).

The C and Python simulators must use the same numbers. Run this after any change to the unit data:

    python tools/gen_unit_data.py

CI runs it with --check and fails when the generated file is out of date.
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "python"))

from am_sdk import units as U  # noqa: E402

OUT = os.path.join(ROOT, "c", "src", "am_unit_data.c")


def f(x):
    return repr(float(x))


def generate() -> str:
    lines = [
        "/* Generated by tools/gen_unit_data.py from python/am_sdk/data. Do not edit. */",
        "/* SPDX-License-Identifier: Apache-2.0 */",
        '#include "am_internal.h"',
        "",
    ]
    entries = []
    for unit in U.UNIT_IDS:
        ud = U.load_unit(unit)
        num, den = U.ratio_fraction(ud.ratio)
        cid = unit.replace("-", "_")
        curves = ud.model._DATA["curves"]
        refs = []
        for bus in ("48", "36"):
            row = []
            for kind in ("peak", "continuous"):
                c = curves[bus][kind]
                if not c["interpolate"] or c["hold_Nm"] is not None:
                    raise SystemExit("%s %s %s: only interpolated curves without hold are supported" % (unit, bus, kind))
                name = "k_%s_%s_%s" % (cid, bus, kind)
                pts = ", ".join("{%s, %s}" % (f(r), f(t)) for r, t in c["points"])
                lines.append("static const am_curve_pt %s[] = {%s};" % (name, pts))
                row.append("{%s, %d}" % (name, len(c["points"])))
            refs.append("{" + ", ".join(row) + "}")
        lines.append("")
        stiff, backlash = ("1005.0", "7260e-6") if unit == "S-S" else ("AM_NAN", "AM_NAN")
        entries.append(
            "    {\"%s\", (am_sku)%d, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %d, %s, %s, %uu, %uu, %s, %s,\n     {%s}}"
            % (unit, int(ud.sku), f(ud.ratio), f(ud.armature_kgm2), f(ud.mass_kg), f(ud.peak_nm), f(ud.rated_nm),
               f(ud.rated_speed_rad_s), f(ud.no_load_rad_s["48"]), f(ud.no_load_rad_s["36"]), f(ud.backdrive_nm),
               f(ud.thermal_tau_s), 1 if ud.thermal_tau_published else 0, f(ud.kt_motor_nm_per_a), f(ud.gear_eta),
               num, den, stiff, backlash, ", ".join(refs)))
    lines.append("const am_unit_data am_unit_table[AM_UNIT_COUNT] = {")
    lines.append(",\n".join(entries))
    lines.append("};")
    lines.append("")
    return "\n".join(lines)


def main():
    text = generate()
    if "--check" in sys.argv:
        with open(OUT, "r", encoding="utf-8") as fh:
            if fh.read() != text:
                raise SystemExit("c/src/am_unit_data.c is out of date: run python tools/gen_unit_data.py")
        print("am_unit_data.c is up to date")
        return
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print("wrote", os.path.relpath(OUT, ROOT))


if __name__ == "__main__":
    main()
